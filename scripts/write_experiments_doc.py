"""Render docs/experiments.md from the real experiment artefacts.

Every number in the generated document is read from:
    experiments/<run>/run_info.json, experiments/<run>/results.csv,
    experiments/<run>/eval_test/metrics.json, experiments/comparison.json
Missing artefacts are rendered as "PENDING" - never estimated.

Usage:  .venv\\Scripts\\python scripts\\write_experiments_doc.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from rdd_yolo.constants import CLASS_CODES, CLASS_NAMES, EXPERIMENTS_DIR  # noqa: E402

RUNS = {"baseline": "baseline_yolo26n", "rdd": "rdd_yolo26n"}


def load(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def time_cell(run: str, info: dict) -> str:
    """Wall time plus the median epoch duration; flags epochs that include a pause (e.g. system sleep)."""
    import csv

    t = [float(r["time"]) for r in csv.DictReader((EXPERIMENTS_DIR / run / "results.csv").open())]
    d = [b - a for a, b in zip([0.0] + t, t)]
    med = sorted(d)[len(d) // 2]
    cell = f"{info['train_time_hours']:.2f} h wall ({info['hardware'].get('gpu_name')}); median epoch {med:.0f} s"
    slow = [(e + 1, x) for e, x in enumerate(d) if x > 5 * med]
    if slow:
        paused = sum(x - med for _, x in slow) / 3600
        cell += (f"; epoch {', '.join(str(e) for e, _ in slow)} took {', '.join(f'{x:,.0f} s' for _, x in slow)} "
                 f"- an idle gap of ≈{paused:.1f} h, most likely the laptop sleeping; no checkpoints were written during it")
    return cell


def pct(v) -> str:
    return "PENDING" if v is None else f"{100 * v:.2f}"


def main() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")  # Windows consoles default to cp1252
    info = {k: load(EXPERIMENTS_DIR / r / "run_info.json") for k, r in RUNS.items()}
    ev = {k: load(EXPERIMENTS_DIR / r / "eval_test" / "metrics.json") for k, r in RUNS.items()}
    cmp_ = load(EXPERIMENTS_DIR / "comparison.json")

    L = ["# Experiments: baseline YOLO26n vs RDD-YOLO26n", "",
         "> Auto-generated by `scripts/write_experiments_doc.py` from the files in `experiments/`.",
         "> Do not edit numbers by hand; re-run the script after re-training.", "",
         "## Setup", "",
         "| | Experiment A — Baseline | Experiment B — RDD-YOLO |", "|---|---|---|",
         "| Architecture | `models/architectures/yolo26-baseline.yaml` (unmodified YOLO26) | `models/architectures/yolo26-rdd.yaml` |",
         "| Modifications | — | SimAM after backbone · bilinear (align_corners) upsampling ×2 · GhostConv for both PAN downsampling convs |"]
    for label, key in (("Epochs completed", "epochs"), ("Training time", "time"), ("Best epoch (val fitness)", "best")):
        row = []
        for k in RUNS:
            i = info[k]
            if not i:
                row.append("PENDING")
            elif key == "epochs":
                row.append(f"{i['results'].get('epochs_completed')} / {i['args'].get('epochs')}")
            elif key == "time":
                row.append(time_cell(RUNS[k], i))
            else:
                row.append(str(i["results"].get("best_epoch_val", {}).get("epoch")))
        L.append(f"| {label} | {row[0]} | {row[1]} |")
    L += ["", "Common settings: RDD2022 subset (Japan, India, Czech, United States, China-MotorBike), 16,156 train / "
          "2,017 val / 2,023 test images, 640 px, batch 16, AMP, seed 0, deterministic, optimizer `auto` (MuSGD), "
          "mosaic off for the last 10 epochs, early-stopping patience 15. Both start from the same initialisation: "
          "COCO-pretrained YOLO26n backbone (layers 0–10), neck and head trained from scratch.", ""]

    L += ["## Test-split results (2,023 held-out images)", ""]
    if cmp_:
        L += ["| Metric (%) | Baseline | RDD-YOLO | Δ (pp) |", "|---|---|---|---|"]
        for k, lbl in (("precision", "Precision"), ("recall", "Recall"), ("f1", "F1"), ("mAP50", "mAP@50"),
                       ("mAP50_95", "mAP@50-95")):
            o = cmp_["overall"][k]
            L.append(f"| {lbl} | {pct(o['baseline'])} | {pct(o['rdd'])} | {100 * o['delta']:+.2f} |")
        e = cmp_["efficiency"]
        L += [f"| Parameters | {e['parameters']['baseline']:,} | {e['parameters']['rdd']:,} | "
              f"{e['parameters']['rdd'] - e['parameters']['baseline']:+,} |",
              f"| GFLOPs (640) | {e['gflops']['baseline']} | {e['gflops']['rdd']} | |",
              f"| Checkpoint size (MB) | {e['model_size_mb']['baseline']} | {e['model_size_mb']['rdd']} | |",
              f"| Inference latency (ms, batch 1) | {e['inference_ms']['baseline']} | {e['inference_ms']['rdd']} | |",
              f"| FPS end-to-end (batch 1) | {e['fps_end_to_end']['baseline']} | {e['fps_end_to_end']['rdd']} | |", "",
              "FPS measured on " + (ev["rdd"] or {}).get("gpu", "?") + " over 200 test images after 20 warm-up runs "
              "(end-to-end = pre-processing + inference + post-processing).", "",
              "### Per-class (test)", "",
              "| Class | Base P | Base R | Base mAP50 | Base mAP50-95 | RDD P | RDD R | RDD mAP50 | RDD mAP50-95 |",
              "|---|---|---|---|---|---|---|---|---|"]
        for c in CLASS_CODES:
            a, b = ev["baseline"]["per_class"].get(c, {}), ev["rdd"]["per_class"].get(c, {})
            L.append(f"| {c} {CLASS_NAMES[c]} | {pct(a.get('precision'))} | {pct(a.get('recall'))} | {pct(a.get('mAP50'))} | "
                     f"{pct(a.get('mAP50_95'))} | {pct(b.get('precision'))} | {pct(b.get('recall'))} | {pct(b.get('mAP50'))} | "
                     f"{pct(b.get('mAP50_95'))} |")
        L += ["", "![Training curves](../experiments/comparison_curves.png)", "",
              "![Test metrics](../experiments/comparison_metrics.png)", ""]
    else:
        L += ["**PENDING** — run `scripts\\train.ps1` (or `scripts\\evaluate.ps1` after training) to produce "
              "`experiments/comparison.json`.", ""]

    if cmp_:
        o, e = cmp_["overall"], cmp_["efficiency"]
        dm, dm95, df1 = (100 * o[k]["delta"] for k in ("mAP50", "mAP50_95", "f1"))
        verdict = ("no meaningful accuracy difference" if max(abs(dm), abs(dm95), abs(df1)) < 1.0
                   else ("RDD-YOLO is more accurate" if dm95 > 0 and dm > 0 else "the baseline is more accurate"
                         if dm95 < 0 and dm < 0 else "mixed accuracy differences"))
        dp = 100 * (e["parameters"]["rdd"] - e["parameters"]["baseline"]) / e["parameters"]["baseline"]
        dfps = 100 * (e["fps_end_to_end"]["rdd"] - e["fps_end_to_end"]["baseline"]) / e["fps_end_to_end"]["baseline"]
        per = {c: 100 * ((cmp_["per_class_mAP50"][c]["rdd"] or 0) - (cmp_["per_class_mAP50"][c]["baseline"] or 0))
               for c in CLASS_CODES}
        L += ["## Findings (computed from the numbers above)", "",
              f"* **Accuracy:** {verdict} on the test split — ΔmAP@50 {dm:+.2f} pp, ΔmAP@50-95 {dm95:+.2f} pp, "
              f"ΔF1 {df1:+.2f} pp (all changes below 1 pp are treated as within single-run noise).",
              "* **Per class (ΔmAP@50, RDD − baseline):** " + ", ".join(f"{c} {v:+.2f} pp" for c, v in per.items()) + ".",
              f"* **Size:** RDD-YOLO has {dp:+.1f} % parameters ({e['parameters']['rdd']:,} vs {e['parameters']['baseline']:,}) "
              f"and {e['gflops']['rdd']} vs {e['gflops']['baseline']} GFLOPs, from the two GhostConv blocks.",
              f"* **Speed:** end-to-end inference FPS {dfps:+.1f} % ({e['fps_end_to_end']['rdd']} vs "
              f"{e['fps_end_to_end']['baseline']})" + (" despite fewer FLOPs — likely because SimAM and bilinear "
              "interpolation are memory-bound element-wise operations that FLOP counts do not capture." if dfps < 0 else "."),
              ]
        if verdict.startswith("no meaningful") and dfps < 0:
            L += ["* **Conclusion for this setup:** the paper's gains (reported for YOLOv8x, 180 epochs, all countries) were "
              "not reproduced at nano scale with 40 epochs; RDD-YOLO matches the baseline's accuracy with a smaller model "
              "but runs slower. A fair test of the paper's claim would need the larger scale, the full schedule and "
              "repeated seeds."]
        L += [""]

    # ---------------- Experiment C (extended data fine-tune)
    c_info = load(EXPERIMENTS_DIR / "rdd_yolo26n_ext" / "run_info.json")
    if c_info:
        stats = load(ROOT / "dataset" / "processed" / "rdd2022_extended" / "dataset_stats.json") or {}
        src = stats.get("images_per_source", {})
        L += ["## Experiment C — RDD-YOLO fine-tuned on extended data", "",
              "Starting from the Experiment B checkpoint, RDD-YOLO26n was fine-tuned for "
              f"{c_info['results']['epochs_completed']} epochs ({c_info['train_time_hours']:.2f} h, "
              f"{c_info['hardware'].get('gpu_name')}, non-deterministic CUDA kernels for ~27 % faster training) on "
              f"{stats.get('images', {}).get('train', 'n/a'):,} training images:", "",
              "| Source | Train | Val | Test |", "|---|---|---|---|"]
        for k, v in src.items():
            t = v.get("test", v.get("test_rdd_new", v.get("test_external", 0)))
            L.append(f"| {k} | {v.get('train', 0):,} | {v.get('val', 0):,} | {t:,} |")
        L += ["", "External pothole sets (Roboflow exports, CC BY 4.0) contribute **only the pothole class (D40)**; "
              "images that also carry their generic \"Crack\" label are excluded "
              f"({stats.get('skipped', {}).get('egypt_rdd: image has generic Crack label', 0):,} images) because those cracks "
              "cannot be mapped to D00/D10/D20. The original test split is unchanged.", "",
              "| Test set | Metric | Exp B (before) | Exp C (after) | Δ (pp) |", "|---|---|---|---|---|"]
        for tag, label in (("test", "Original RDD2022 test"), ("test_rdd_new", "Norway + China_Drone held-out"),
                           ("test_external", "Ground-level potholes (external)")):
            b = load(EXPERIMENTS_DIR / "rdd_yolo26n" / f"eval_{tag}" / "metrics.json")
            c = load(EXPERIMENTS_DIR / "rdd_yolo26n_ext" / f"eval_{tag}" / "metrics.json")
            if not (b and c):
                continue
            for k, lbl in (("precision", "Precision"), ("recall", "Recall"), ("mAP50", "mAP@50"), ("mAP50_95", "mAP@50-95")):
                L.append(f"| {label} ({c['images']} imgs) | {lbl} | {pct(b['overall'][k])} | {pct(c['overall'][k])} | "
                         f"{100 * (c['overall'][k] - b['overall'][k]):+.2f} |")
        L += ["", "Note: C received more data *and* more epochs than B, so the gain cannot be attributed to the data alone.", ""]

    # ---------------- Experiment D (extended v2: + close-up pothole datasets, de-duplicated)
    d_info = load(EXPERIMENTS_DIR / "rdd_yolo26n_ext2" / "run_info.json")
    if d_info:
        st = load(ROOT / "dataset" / "processed" / "rdd2022_extended_v2" / "dataset_stats_v2.json") or {}
        added, skipped = st.get("added", {}), st.get("skipped", {})
        n_train = sum(v for k, v in added.items() if k.endswith("/train"))
        n_dup = sum(v for k, v in skipped.items() if "duplicate" in k)
        n_leak = sum(v for k, v in skipped.items() if "duplicates a test image" in k) + st.get("removed_round1_external_duplicates", 0)
        L += ["## Experiment D — + close-up pothole datasets (served model)", "",
              f"Fine-tuned from Experiment C for {d_info['results']['epochs_completed']} epochs "
              f"({d_info['train_time_hours']:.2f} h, {d_info['hardware'].get('gpu_name')}) on "
              f"{st.get('images', {}).get('train', 'n/a'):,} training images. Added {n_train:,} close-up/ground-level pothole "
              "training images from six public datasets with stated licenses (CC BY 4.0: manot/pothole-segmentation, "
              "manot/pothole-segmentation2, keremberke/pothole-segmentation; MIT: rupesh002 ×2; Apache-2.0: sumadixSk MWPD). "
              f"De-duplication by 64-bit dHash (incl. mirrored images, Hamming ≤ {st.get('hamming_threshold')}) removed {n_dup:,} "
              f"duplicate images, of which {n_leak:,} matched a held-out test image (leakage prevented). Their own test "
              f"splits form a new held-out **close-up pothole test set** ({st.get('images', {}).get('test_closeup', 0)} images).", "",
              "| Test set | Metric | B | C | D (served) |", "|---|---|---|---|---|"]
        for tag, label in (("test", "Original RDD2022 test"), ("test_rdd_new", "Norway + China_Drone"),
                           ("test_external", "Ground-level potholes"), ("test_closeup", "Close-up potholes (new)")):
            ms = [load(EXPERIMENTS_DIR / r / f"eval_{tag}" / "metrics.json") for r in ("rdd_yolo26n", "rdd_yolo26n_ext", "rdd_yolo26n_ext2")]
            if not all(ms):
                continue
            for k, lbl in (("precision", "Precision"), ("recall", "Recall"), ("mAP50", "mAP@50"), ("mAP50_95", "mAP@50-95")):
                L.append(f"| {label} ({ms[2]['images']} imgs) | {lbl} | " + " | ".join(pct(m['overall'][k]) for m in ms) + " |")
        L += ["", "Experiment D is the model served by the application (`models/weights/rdd_yolo26n_ext2_best.pt`). "
              "Each step adds data *and* epochs, so improvements are not attributable to data alone.", ""]

    # ---------------- Experiment E (YOLO26s, full COCO init, extended v3)
    e_info = load(EXPERIMENTS_DIR / "yolo26s_full" / "run_info.json")
    if e_info:
        st = load(ROOT / "dataset" / "processed" / "rdd2022_extended_v3" / "dataset_stats_v3.json") or {}
        sk = st.get("skipped", {})
        n_leak = sum(v for k, v in sk.items() if "duplicates a test image" in k)
        n_added = sum(v for k, v in st.get("added", {}).items() if k.endswith("/train"))
        L += ["## Experiment E — YOLO26s (latest Ultralytics architecture, small scale)", "",
              f"Unmodified YOLO26**s** ({e_info['scale']} scale) initialised with the official COCO weights in *all* "
              f"shape-compatible layers ({e_info['initialisation'].get('transferred_tensors')} of "
              f"{e_info['initialisation'].get('model_tensors')} tensors), trained for {e_info['results']['epochs_completed']} "
              f"epochs ({e_info['train_time_hours']:.2f} h, batch 8, {e_info['hardware'].get('gpu_name')}) on "
              f"{st.get('images', {}).get('train', 'n/a'):,} training images: the v2 set plus {n_added:,} images from the "
              "MIT-licensed *Pavement Distress Detection* aggregate (Hugging Face Deeksha9; sources SVRDD, HighRPD, RD0 and "
              "an unnamed 'archive' set). Its RDD2022 copy and older Japanese RDD release were not used (they overlap our "
              f"test split); {n_leak:,} further images matching a held-out test image were removed by dHash. Its test split "
              f"forms a fifth held-out set (**test_pavement**, {st.get('images', {}).get('test_pavement', 0):,} images). "
              "Note: E is not RDD-YOLO (no SimAM/GhostConv/bilinear) — it is the plain latest architecture at a larger scale.", "",
              "| Test set | Metric | D (RDD-YOLO26n ext2) | E (YOLO26s) | Δ (pp) |", "|---|---|---|---|---|"]
        for tag, label in (("test", "Original RDD2022 test"), ("test_rdd_new", "Norway + China_Drone"),
                           ("test_external", "Ground-level potholes"), ("test_closeup", "Close-up potholes"),
                           ("test_pavement", "Pavement-distress sources (new)")):
            a = load(EXPERIMENTS_DIR / "rdd_yolo26n_ext2" / f"eval_{tag}" / "metrics.json")
            b = load(EXPERIMENTS_DIR / "yolo26s_full" / f"eval_{tag}" / "metrics.json")
            if not (a and b):
                continue
            for k, lbl in (("precision", "Precision"), ("recall", "Recall"), ("mAP50", "mAP@50"), ("mAP50_95", "mAP@50-95")):
                L.append(f"| {label} ({b['images']} imgs) | {lbl} | {pct(a['overall'][k])} | {pct(b['overall'][k])} | "
                         f"{100 * (b['overall'][k] - a['overall'][k]):+.2f} |")
        a = load(EXPERIMENTS_DIR / "rdd_yolo26n_ext2" / "eval_test" / "metrics.json")
        b = load(EXPERIMENTS_DIR / "yolo26s_full" / "eval_test" / "metrics.json")
        if a and b:
            L += ["", f"Size/speed: {a['parameters']:,} → {b['parameters']:,} parameters, {a['model_size_mb']} → "
                  f"{b['model_size_mb']} MB, {a['speed_benchmark']['fps_end_to_end']} → {b['speed_benchmark']['fps_end_to_end']} "
                  "FPS end-to-end (batch 1). D and E differ in architecture, scale, initialisation, data and epochs at once, "
                  "so the comparison shows the overall effect, not the contribution of any single factor.", ""]

    L += ["## Generated artefacts", "",
          "* `experiments/<run>/results.csv` / `results.png` — per-epoch losses (box, cls, L1) and val P/R/mAP",
          "* `experiments/<run>/eval_test/` — confusion matrix (raw + normalised), PR / P / R / F1 curves, prediction mosaics, `metrics.json`",
          "* `experiments/comparison.{json,md}` and `comparison_*.png`",
          "* The dashboard's *Training & Experiments* page renders the same files.", "",
          "## Interpretation guidelines", "",
          "* Differences of a few tenths of a percentage point between two single training runs are within run-to-run "
          "noise (no repeated seeds were run due to the hardware budget); treat such gaps as \"no significant difference\".",
          "* The paper (YOLOv8x, all six countries, 180 epochs, RTX 4090) reports +2.5 pp mAP50 for RDD-YOLO; "
          "our nano-scale, 40-epoch, 5-country setup is not directly comparable.",
          "* SimAM and bilinear upsampling add no parameters; GhostConv removes parameters, so RDD-YOLO is smaller "
          "by construction; their effect on speed is whatever the measured latency/FPS rows above show.",
          ""]
    out = ROOT / "docs" / "experiments.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
